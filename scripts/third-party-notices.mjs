#!/usr/bin/env node
// Generate NOTICE from the production npm dependency tree and the Cargo.lock
// dependency graph. Output is deterministic: sorted by component name/version
// and free of timestamps or machine paths.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";

const root = process.cwd();
const lockPath = path.join(root, "package-lock.json");
const cargoManifest = path.join(root, "src-tauri");

// The package omits a license field from package.json; its `license` file and
// README both state MIT (verified manually).
const LICENSE_OVERRIDES = new Map([["khroma", "MIT"]]);

function normalizeLicense(value) {
  if (value === undefined || value === null) return null;
  if (typeof value === "string") {
    const text = value.replace(/\s+/g, " ").trim();
    return text.length > 0 ? text : null;
  }
  if (typeof value === "object" && typeof value.type === "string") {
    return value.type;
  }
  return null;
}

const lock = JSON.parse(readFileSync(lockPath, "utf8"));
const npmRows = new Map();
for (const [key, meta] of Object.entries(lock.packages ?? {})) {
  if (!key.startsWith("node_modules/")) continue;
  if (meta.dev === true) continue;
  const marker = "node_modules/";
  const name = key.slice(key.lastIndexOf(marker) + marker.length);
  const version = meta.version;
  if (typeof version !== "string" || version.length === 0) continue;
  let license = normalizeLicense(meta.license);
  const packageJsonPath = path.join(root, key, "package.json");
  if (license === null && existsSync(packageJsonPath)) {
    try {
      license = normalizeLicense(JSON.parse(readFileSync(packageJsonPath, "utf8")).license);
    } catch {
      license = null;
    }
  }
  const id = `${name}@${version}`;
  if (!npmRows.has(id)) {
    npmRows.set(id, {
      name,
      version,
      license: license ?? LICENSE_OVERRIDES.get(name) ?? "UNKNOWN",
    });
  }
}

const cargo = spawnSync(
  "cargo",
  ["metadata", "--locked", "--format-version", "1"],
  { cwd: cargoManifest, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
);
if (cargo.status !== 0) {
  process.stderr.write(cargo.stderr ?? "");
  throw new Error("cargo metadata failed");
}
const metadata = JSON.parse(cargo.stdout);
const rustRows = new Map();
for (const pkg of metadata.packages ?? []) {
  // The workspace package has no source; everything else is a third-party
  // dependency (registry, git, or path).
  if (!pkg.source) continue;
  const license =
    normalizeLicense(pkg.license) ??
    (pkg.license_file ? `see ${path.basename(pkg.license_file)}` : "UNKNOWN");
  const id = `${pkg.name}@${pkg.version}`;
  if (!rustRows.has(id)) {
    rustRows.set(id, { name: pkg.name, version: pkg.version, license });
  }
}

function table(rows) {
  const sorted = [...rows.values()].sort((a, b) =>
    a.name === b.name ? a.version.localeCompare(b.version) : a.name.localeCompare(b.name),
  );
  const lines = ["| Component | Version | License |", "| --- | --- | --- |"];
  for (const row of sorted) {
    lines.push(`| ${row.name} | ${row.version} | ${row.license} |`);
  }
  return { text: lines.join("\n"), unknown: sorted.filter((row) => row.license === "UNKNOWN") };
}

const npm = table(npmRows);
const rust = table(rustRows);
const unknown = [...npm.unknown, ...rust.unknown];

const mit = readFileSync(path.join(root, "LICENSE"), "utf8").trim();
const apache = readFileSync(path.join(root, "assets", "legal", "APACHE-2.0.txt"), "utf8").trim();

const output = `# Third-Party Notices

Knowwise is licensed under the MIT License. This file lists third-party
components used by the project and their licenses. It is generated by
\`npm run notices\` from \`package-lock.json\` and \`src-tauri/Cargo.lock\`;
do not edit it by hand.

The npm table covers production dependencies that can be bundled into the
frontend. Development-only packages used to build and test the project remain
in \`package-lock.json\` and are not distributed. The Rust table covers the
locked Cargo dependency graph, including build and test dependencies.

## npm dependencies (production)

${npm.text}

## Rust dependencies

${rust.text}

## Optional local translation assets (not redistributed)

These assets are downloaded by \`scripts/install-models.mjs\` at the user's
request. They are not part of this repository or its installers.

| Asset | License | Attribution |
| --- | --- | --- |
| OPUS-MT zh-en / en-zh quantized ONNX weights | CC-BY-4.0 | Helsinki-NLP, University of Helsinki; ONNX conversion by Xenova |
| ONNX Runtime 1.23.2 native library | MIT | Microsoft |
| Tesseract.js language data (eng, chi_sim) | Apache-2.0 | Tesseract OCR / tessdata |

The MIT and Apache-2.0 license texts are reproduced below. Other licenses
listed in the tables (for example BSD, ISC, MPL-2.0, Unicode-3.0, Zlib and
CC-BY-4.0) are identified by their SPDX expression; the corresponding
license texts are included in the distributed dependency packages.

${unknown.length > 0 ? `## Components with missing license metadata\n\n${unknown.map((row) => `- ${row.name}@${row.version}`).join("\n")}\n\nThese components require a manual license check before release.\n\n` : ""}## License texts

### MIT License

${mit}

---

### Apache License, Version 2.0

${apache}
`;

writeFileSync(path.join(root, "NOTICE"), `${output.trimEnd()}\n`, "utf8");
console.log(
  `NOTICE written: ${npmRows.size} npm components, ${rustRows.size} Rust components, ${unknown.length} missing license fields`,
);
